// The gallery's built-in examples, shown until real published work fills it.
//
// Prompts are never written here. A clip whose original prompt is on file
// (home-example-prompts.json) shows that prompt and remixes by sample ID; the
// rest use SAMPLE_PROMPTS, which describes what is actually in the picture.
// Titles and descriptions say what the picture shows; aspect ratio and duration
// are the file's own. Look at the media before changing any of it: on
// 2026-11-27 eleven of the twelve entries described something else (a "golden
// cloud dragon" that was a jungle flight, a "daylight studio" that was a night
// one), and Remix sent visitors off with a prompt that could not make the clip.
// tests/curated-gallery.test.ts holds the prompt rule.
import examplePrompts from "@/lib/home-example-prompts.json";
import type { GalleryItem } from "@/lib/gallery";
import { SAMPLE_PROMPTS } from "@/lib/home-showcase";

export type CuratedCategory = "video" | "cinema" | "commercial";
export type SampleId = keyof typeof examplePrompts;

const EXAMPLE_PROMPTS: Record<SampleId, string> = examplePrompts;

function described(asset: string, zh: boolean): string {
  const prompt = SAMPLE_PROMPTS[asset];
  if (!prompt) throw new Error(`No SAMPLE_PROMPTS entry for ${asset}: describe the picture there first.`);
  return zh ? prompt.zh : prompt.en;
}

