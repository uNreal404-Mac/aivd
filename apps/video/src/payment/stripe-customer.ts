import type Stripe from "stripe";
import { eq } from "drizzle-orm";

import { customers, db } from "@/db";

/**
 * What the account page and the billing portal need to know about a Stripe
 * subscriber. The plan tier itself comes from the credit grants
 * (`getUserPlanTier`), so this row only links the account to Stripe.
 */
export interface StripeSubscriberRecord {
  userId: string;
  stripeCustomerId: string;
  subscriptionId: string;
  /** `false` once the subscription has ended (canceled or expired). */
  active: boolean;
  /**
   * When the subscription next renews. `null` when it will not renew (set to
   * cancel at period end, or already ended), so the page never shows a
   * renewal date that will not happen. `undefined` leaves the stored date
   * alone (checkout completion does not carry it).
   */
  renewsAt?: Date | null;
}

export type RecordStripeSubscriber = (record: StripeSubscriberRecord) => Promise<void>;

/**
 * Upserts the account's Customer row, keyed by user id.
 *
 * An ended subscription only clears the stored one when it is the same
 * subscription, so the end of an old subscription never hides a newer one.
 */
export const recordStripeSubscriber: RecordStripeSubscriber = async ({
  userId,
  stripeCustomerId,
  subscriptionId,
  active,
  renewsAt,
}) => {
  const [existing] = await db
    .select({ id: customers.id, stripeSubscriptionId: customers.stripeSubscriptionId })
    .from(customers)
    .where(eq(customers.authUserId, userId))
    .limit(1);

  const values: Partial<typeof customers.$inferInsert> = {
    stripeCustomerId,
    updatedAt: new Date(),
  };
  const current = existing?.stripeSubscriptionId ?? null;
  if (active) {
    values.stripeSubscriptionId = subscriptionId;
    if (renewsAt !== undefined) values.stripeCurrentPeriodEnd = renewsAt;
  } else if (current === null || current === subscriptionId) {
    values.stripeSubscriptionId = null;
    values.stripeCurrentPeriodEnd = null;
  }

  if (existing) {
    await db.update(customers).set(values).where(eq(customers.id, existing.id));
    return;
  }
  await db.insert(customers).values({ authUserId: userId, stripeCustomerId, ...values });
};

/** Stripe id of an expandable field, whether it came as an id or an object. */
export function stripeIdOf(value: string | { id: string } | null | undefined): string | null {
  if (!value) return null;
  return typeof value === "string" ? value : value.id;
}

function isEnded(subscription: Stripe.Subscription): boolean {
  return subscription.status === "canceled" || subscription.status === "incomplete_expired";
}

/**
 * Next renewal of a subscription, or `null` when it will not renew.
 *
 * Current API versions put `current_period_end` on each subscription item;
 * older ones (the version Stripe SDK v14 types) put it on the subscription.
 */
export function renewalDateOf(subscription: Stripe.Subscription): Date | null {
  if (isEnded(subscription) || subscription.cancel_at_period_end || subscription.cancel_at) return null;

  const legacy = (subscription as { current_period_end?: number | null }).current_period_end;
  const item = subscription.items?.data?.[0] as { current_period_end?: number | null } | undefined;
  const seconds = item?.current_period_end ?? legacy;
  return typeof seconds === "number" && seconds > 0 ? new Date(seconds * 1000) : null;
}

/** The record for one Stripe subscription, or `null` when it is not ours. */
export function subscriberRecordOf(subscription: Stripe.Subscription): StripeSubscriberRecord | null {
  const userId = subscription.metadata?.userId;
  const stripeCustomerId = stripeIdOf(subscription.customer);
  if (!userId || !stripeCustomerId) return null;
  return {
    userId,
    stripeCustomerId,
    subscriptionId: subscription.id,
    active: !isEnded(subscription),
    renewsAt: renewalDateOf(subscription),
  };
}

/**
 * Finds the Stripe customer for an account that has no Customer row yet:
 * subscriptions bought before the webhook recorded subscribers, or whose
 * webhook was missed. Checkout copies `userId` into the subscription's
 * metadata, which Stripe's search API can query.
 *
 * Returns the newest matching subscription's record, or `null`.
 *
 * @see https://docs.stripe.com/search#query-fields-for-subscriptions
 */
export async function findStripeSubscriber(
  stripe: Stripe,
  userId: string,
): Promise<StripeSubscriberRecord | null> {
  // Ids are generated by Better Auth (no quotes), but escape anyway.
  const safeId = userId.replace(/['\\]/g, "\\$&");
  const result = await stripe.subscriptions.search({
    query: `metadata['userId']:'${safeId}'`,
    limit: 10,
  });
  const newest = [...result.data].sort((a, b) => b.created - a.created);
  const live = newest.find((sub) => !isEnded(sub));
  const pick = live ?? newest[0];
  return pick ? subscriberRecordOf(pick) : null;
}
